export const getStockStatus = (stock, daysLeft) => {
  if (stock === 0) return { label: 'Out of Stock', color: 'red', urgent: true };
  if (stock <= 10 || daysLeft <= 7) return { label: `Only ${stock} left!`, color: 'red', urgent: true };
  if (stock <= 30 || daysLeft <= 15) return { label: 'Low Stock', color: 'yellow', urgent: false };
  return { label: 'In Stock', color: 'green', urgent: false };
};

export const getDiscountPercent = (price, originalPrice) => {
  if (!originalPrice || originalPrice <= price) return 0;
  return Math.round(((originalPrice - price) / originalPrice) * 100);
};
